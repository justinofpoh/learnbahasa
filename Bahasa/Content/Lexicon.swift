import Foundation

/// A pocket dictionary for every word in the Scenes. Tap a word in a conversation to look it up.
/// Endings (-nya, -mu, -ku) and doubled words (lihat-lihat) are understood from their base.
/// Indonesian here still needs the native-speaker check (spec §12.1).
enum Lexicon {
    struct Entry {
        let word: String
        let meaning: String
        let role: Role
        var note: String?
    }

    struct Result {
        let shown: String        // the word as tapped
        let entry: Entry         // the base entry
        var extra: String?       // what an ending or doubling adds
    }

    static func lookup(_ raw: String) -> Result? {
        let w = raw.lowercased().trimmingCharacters(in: CharacterSet.letters.union(CharacterSet(charactersIn: "-")).inverted)
        guard !w.isEmpty else { return nil }
        if let e = entries[w] { return Result(shown: w, entry: e) }
        if let place = places[w] {
            return Result(shown: w, entry: Entry(word: w, meaning: place, role: .object, note: "A place name. Names stay the same in Indonesian."))
        }
        if let country = SceneLibrary.pack.countries.first(where: { $0.local.lowercased() == w }) {
            return Result(shown: w, entry: Entry(word: w, meaning: country.en, role: .object,
                                                 note: country.local == country.en ? nil : "Country names often change a little: \(country.en) is \(country.local)."))
        }

        let endings: [(String, String)] = [
            ("-nya", "-nya points at something you both know: \u{201C}the\u{201D}, \u{201C}its\u{201D} or \u{201C}your\u{201D}."),
            ("-mu", "-mu means \u{201C}your\u{201D} (casual)."),
            ("nya", "-nya points at something you both know: \u{201C}the\u{201D}, \u{201C}its\u{201D} or \u{201C}your\u{201D}."),
            ("mu", "-mu means \u{201C}your\u{201D} (casual)."),
            ("ku", "-ku means \u{201C}my\u{201D} (casual).")
        ]
        for (ending, note) in endings where w.hasSuffix(ending) && w.count > ending.count + 1 {
            let base = String(w.dropLast(ending.count))
            if let e = entries[base] { return Result(shown: w, entry: e, extra: note) }
        }
        let parts = w.split(separator: "-").map(String.init)
        if parts.count == 2, parts[0] == parts[1], let e = entries[parts[0]] {
            return Result(shown: w, entry: e, extra: "Doubled words soften or spread the meaning: lihat-lihat is \u{201C}just looking around\u{201D}.")
        }
        return nil
    }

