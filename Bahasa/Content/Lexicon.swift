        "lombok": "Lombok", "surabaya": "Surabaya"
    ]

    private static func e(_ word: String, _ meaning: String, _ role: Role, _ note: String? = nil) -> (String, Entry) {
        (word, Entry(word: word, meaning: meaning, role: role, note: note))
    }

